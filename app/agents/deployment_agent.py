"""Deployment Agent - Generates deployment configuration files."""

from __future__ import annotations

import os
from typing import Any, Dict

from app.agents.base_agent import BaseAgent
from app.agents.project_context import ProjectContext
from app.core.logger import Logger


class DeploymentAgent(BaseAgent):
    """Generates Docker, CI/CD, and deployment configurations."""

    agent_id = "deployment"
    capabilities = ("deployment", "docker", "ci", "cd", "devops", "deploy")

    def run(self, context) -> Dict[str, Any]:
        if isinstance(context, dict):
            context = ProjectContext(**{k: v for k, v in context.items() if k in ProjectContext.__dataclass_fields__})
        
        project_path = context.project_path or ""
        if not project_path or not os.path.isdir(project_path):
            context.add_log("No project path available, skipping deployment config")
            return {
                "success": True,
                "output": {"skipped": True, "reason": "No project path"},
                "context": context,
            }

        Logger.info("[DeploymentAgent] Generating deployment configs")
        context.current_task = "deployment_config"
        context.add_log("Starting deployment configuration")

        # Deployment files are generated by the project builder in Phase 1
        # This agent validates and enhances them
        self._ensure_deployment_files(project_path)
        context.add_completed_task("deployment_config")
        context.add_log("Deployment configuration complete")
        context.set_metric("deployment_files", True)

        return {
            "success": True,
            "output": {"status": "configured"},
            "context": context,
        }

    @staticmethod
    def _ensure_deployment_files(project_path: str):
        """Ensure basic deployment files exist."""
        dockerfile = os.path.join(project_path, "Dockerfile")
        if not os.path.exists(dockerfile):
            with open(dockerfile, "w", encoding="utf-8") as f:
                f.write("FROM python:3.11-slim\nWORKDIR /app\nCOPY . .\nRUN pip install -r requirements.txt\nCMD [\"python\", \"main.py\"]\n")
